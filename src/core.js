/**
 * Error thrown when an invalid EUC-KR byte sequence is encountered.
 */
export class EucKrError extends Error {
  constructor(message, offset) {
    super(message);
    this.name = 'EucKrError';
    this.offset = offset;
  }
}

/**
 * Decodes a single EUC-KR character starting at `offset`.
 *
 * Returns an object with `codePoint` (Unicode code point), `bytes` (number of bytes
 * consumed), and `offset` (the starting offset).
 *
 * Throws `EucKrError` for malformed input. The decoder is strict: a lead byte in the
 * range 0x81..0xFE must be followed by a trail byte in 0xA1..0xFE. Any other byte is
 * treated as an error. This matches the behaviour of the EUC-KR encoding used by
 * Korean systems and avoids silently producing U+FFFD for every malformed byte.
 */
export function decodeEucKrChar(bytes, offset = 0) {
  if (!(bytes instanceof Uint8Array)) {
    throw new TypeError('bytes must be a Uint8Array');
  }
  if (offset < 0 || offset >= bytes.length) {
    throw new EucKrError('offset out of range', offset);
  }
  const b0 = bytes[offset];
  if (b0 < 0x80) {
    return { codePoint: b0, bytes: 1, offset };
  }
  if (b0 < 0x81 || b0 > 0xfe) {
    throw new EucKrError(`invalid lead byte 0x${b0.toString(16)}`, offset);
  }
  if (offset + 1 >= bytes.length) {
    throw new EucKrError('truncated multi-byte sequence', offset);
  }
  const b1 = bytes[offset + 1];
  if (b1 < 0xa1 || b1 > 0xfe) {
    throw new EucKrError(`invalid trail byte 0x${b1.toString(16)}`, offset + 1);
  }
  const row = b0 - 0xa1;
  const col = b1 - 0xa1;
  const codePoint = KSX1001_TABLE[row * 94 + col];
  if (codePoint === -1) {
    throw new EucKrError(
      `unassigned EUC-KR code 0x${b0.toString(16)} 0x${b1.toString(16)}`,
      offset
    );
  }
  return { codePoint, bytes: 2, offset };
}

/**
 * Decodes an entire EUC-KR byte array into a JavaScript string.
 *
 * The decoder never inserts replacement characters. Malformed input causes an
 * `EucKrError` to be thrown, which keeps the API honest: callers that want to
 * tolerate corruption can catch the error and inspect `err.offset`.
 */
export function decodeEucKr(bytes) {
  if (!(bytes instanceof Uint8Array)) {
    throw new TypeError('bytes must be a Uint8Array');
  }
  const parts = [];
  let offset = 0;
  while (offset < bytes.length) {
    const { codePoint, bytes: consumed } = decodeEucKrChar(bytes, offset);
    parts.push(String.fromCodePoint(codePoint));
    offset += consumed;
  }
  return parts.join('');
}

/**
 * Stateful decoder that accepts byte chunks incrementally.
 *
 * Useful when reading from a stream: a multi-byte sequence may be split across
 * chunk boundaries, so the decoder buffers a dangling lead byte until the next
 * chunk arrives. Call `flush()` at the end to surface a truncated sequence.
 */
export class EucKrDecoder {
  constructor() {
    this._pending = null;
  }

  /**
   * Feeds a chunk of bytes and returns the decoded string so far.
   * The returned string may be empty if the chunk ended mid-character.
   */
  write(chunk) {
    if (!(chunk instanceof Uint8Array)) {
      throw new TypeError('chunk must be a Uint8Array');
    }
    let bytes;
    if (this._pending !== null) {
      const merged = new Uint8Array(chunk.length + 1);
      merged[0] = this._pending;
      merged.set(chunk, 1);
      bytes = merged;
      this._pending = null;
    } else {
      bytes = chunk;
    }
    const parts = [];
    let offset = 0;
    while (offset < bytes.length) {
      const b0 = bytes[offset];
      if (b0 < 0x80) {
        parts.push(String.fromCodePoint(b0));
        offset += 1;
        continue;
      }
      if (b0 < 0x81 || b0 > 0xfe) {
        throw new EucKrError(`invalid lead byte 0x${b0.toString(16)}`, offset);
      }
      if (offset + 1 >= bytes.length) {
        this._pending = b0;
        break;
      }
      const b1 = bytes[offset + 1];
      if (b1 < 0xa1 || b1 > 0xfe) {
        throw new EucKrError(`invalid trail byte 0x${b1.toString(16)}`, offset + 1);
      }
      const row = b0 - 0xa1;
      const col = b1 - 0xa1;
      const codePoint = KSX1001_TABLE[row * 94 + col];
      if (codePoint === -1) {
        throw new EucKrError(
          `unassigned EUC-KR code 0x${b0.toString(16)} 0x${b1.toString(16)}`,
          offset
        );
      }
      parts.push(String.fromCodePoint(codePoint));
      offset += 2;
    }
    return parts.join('');
  }

  /**
   * Signals end of input. Throws if a lead byte was left dangling.
   */
  flush() {
    if (this._pending !== null) {
      const offset = this._pending;
      this._pending = null;
      throw new EucKrError('truncated multi-byte sequence at end of stream', offset);
    }
  }
}
