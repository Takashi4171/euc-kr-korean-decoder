// Complete KS X 1001 mapping table (94x94).
// Each entry is either a Unicode code point or -1 for an unassigned slot.
const KSX1001_TABLE = new Int32Array(94 * 94).fill(-1);

function setKsx1001(lead, trail, codePoint) {
  const row = lead - 0xa1;
  const col = trail - 0xa1;
  if (row < 0 || row >= 94 || col < 0 || col >= 94) {
    return;
  }
  KSX1001_TABLE[row * 94 + col] = codePoint;
}

